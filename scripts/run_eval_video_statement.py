#!/usr/bin/env python3
"""Thin CLI wrapper around services/evaluation/run_eval_video_statement.py.

Generates a video statement SCRIPT (not a video) with each system. See
services/video_engine/generate.py's module docstring: no synthetic
likeness of the applicant is ever generated by this project.

Usage:
  python scripts/run_eval_video_statement.py                                   # mock LLM, hash embeddings
  python scripts/run_eval_video_statement.py mock video_statement_mock fastembed
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(REPO_ROOT / ".env")

from services.evaluation.run_eval_video_statement import run  # noqa: E402


def main() -> None:
    provider = sys.argv[1] if len(sys.argv) > 1 else None
    tag = sys.argv[2] if len(sys.argv) > 2 else "latest"
    embedding_provider = sys.argv[3] if len(sys.argv) > 3 else None
    summary = run(provider_name=provider, tag=tag, embedding_provider_name=embedding_provider)
    print(json.dumps(summary["scores"], indent=2))
    print(f"\nGenerated scripts: data/evaluation/results/{tag}/documents/")


if __name__ == "__main__":
    main()
